"use server";

import { revalidatePath } from "next/cache";

import type { JobCategory, JobStatus } from "@/domain/types";
import { isJobCategory, isJobStatus } from "@/domain/validation";
import { createJob, deleteJob, updateJob, type JobInput } from "@/services/job-service";
import { assertAuthenticatedAdmin } from "@/lib/auth";

export type JobActionResult = { ok: true } | { ok: false; error: string };

function errorMessage(error: unknown): string {
  if (error instanceof Error) return error.message;
  return "An unexpected error occurred.";
}

async function run(action: () => Promise<unknown>): Promise<JobActionResult> {
  try {
    await assertAuthenticatedAdmin();
    await action();
    revalidatePath("/jobs");
    revalidatePath("/dashboard");
    revalidatePath("/finance");
    return { ok: true };
  } catch (error) {
    return { ok: false, error: errorMessage(error) };
  }
}

/**
 * Membentuk input job kanonik dari nilai form.
 * - Counterparty: client XOR vendor (aturan kanonik; divalidasi repository + CHECK DB).
 * - Job number is generated by the database-backed sequence on create.
 * - Venue tidak ada; `legacyVenueName` hanya snapshot histori optional.
 */
function jobInputFrom(values: Record<string, string>): JobInput {
  const category = (values.category || "WEDDING") as JobCategory;
  if (!isJobCategory(category)) throw new Error("Invalid job category.");
  const status = (values.status || "NOT_STARTED") as JobStatus;
  if (!isJobStatus(status)) throw new Error("Invalid job status.");

  const counterpartyType = values.counterpartyType === "VENDOR" ? "VENDOR" : "CLIENT";
  const counterpartyId = values.counterpartyId?.trim();
  if (!counterpartyId) {
    throw new Error("A job must be linked to either a client or a vendor.");
  }

  const executionDate = values.executionDate?.trim();
  if (!executionDate) throw new Error("Event date is required.");

  return {
    jobNumber: values.jobNumber?.trim() || undefined,
    jobName: values.jobName?.trim() || "",
    category,
    clientId: counterpartyType === "CLIENT" ? counterpartyId : undefined,
    vendorId: counterpartyType === "VENDOR" ? counterpartyId : undefined,
    packageId: values.packageId?.trim() || undefined,
    executionDate,
    status,
    location: values.location?.trim() || undefined,
    notes: values.notes?.trim() || undefined,
    legacyVenueName: values.legacyVenueName?.trim() || undefined,
  };
}

export async function createJobAction(
  values: Record<string, string>,
): Promise<JobActionResult> {
  return run(() => createJob(jobInputFrom(values)));
}

export async function updateJobAction(
  id: string,
  values: Record<string, string>,
): Promise<JobActionResult> {
  return run(() => updateJob(id, jobInputFrom(values)));
}

export async function deleteJobAction(id: string): Promise<JobActionResult> {
  return run(() => deleteJob(id));
}
